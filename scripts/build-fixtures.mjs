#!/usr/bin/env node
// Builds fixtures/snapshot.json for offline mode by running the REAL SQL files in an
// in-process Postgres (PGlite) and exporting the governed views. Offline = same logic as live.
//   npm run build:fixtures
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { sqlFiles, readSql } from './sql-files.mjs';

const OUT = fileURLToPath(new URL('../fixtures/snapshot.json', import.meta.url));
const db = new PGlite({ parsers: { 1082: v => v, 1700: v => Number(v) } });
for (const f of sqlFiles({ includeRole: false })) await db.exec(readSql(f));
const all = async sql => (await db.query(sql)).rows;

const config = Object.fromEntries((await all('SELECT key, value FROM app.config')).map(r => [r.key, r.value]));
const snapshot = {
  built_at: config.demo_today,
  note: 'Generated by scripts/build-fixtures.mjs from db/sql. Do not edit by hand. All data is fictional.',
  config,
  transfer: (await all('SELECT * FROM app.v_transfers'))[0],
  sellers: await all('SELECT * FROM app.v_sellers ORDER BY seller_id'),
  accounts: await all('SELECT * FROM app.v_accounts ORDER BY amount DESC, name'),
  patterns: await all('SELECT * FROM app.v_pattern_steps ORDER BY step_id'),
  evidence: await all('SELECT * FROM app.v_evidence ORDER BY evidence_id'),
  context: await all('SELECT * FROM app.v_saleslore_context ORDER BY account_id, item_type, sort_order, item_key'),
  graph_nodes: await all('SELECT * FROM app.v_graph_nodes ORDER BY node_id'),
  graph_edges: await all('SELECT * FROM app.v_graph_edges ORDER BY edge_id'),
  audit_seed: [
    { at: '2026-10-28T16:12:00Z', actor: 'Maya Okafor', action: 'consent', account_id: null, detail: 'Granted consent to capture her book and working patterns' },
    { at: '2026-11-01T21:03:00Z', actor: 'Pattern distiller', action: 'distill', account_id: null, detail: 'Proposed 8 pattern steps for Maya Okafor' },
    { at: '2026-11-04T17:40:00Z', actor: 'Maya Okafor', action: 'review', account_id: null, detail: 'Approved 6 steps, edited PS-03, rejected PS-08' },
    { at: '2026-11-10T16:00:00Z', actor: 'Dana Whitfield', action: 'transfer_start', account_id: null, detail: 'Started transfer TR-001: Maya Okafor to Leo Brandt, 10 accounts' },
  ],
};
fs.mkdirSync(fileURLToPath(new URL('../fixtures/', import.meta.url)), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + '\n');
console.log(`wrote fixtures/snapshot.json: ${snapshot.accounts.length} accounts, ${snapshot.context.length} context rows, ${snapshot.graph_nodes.length} nodes, ${snapshot.graph_edges.length} edges`);
await db.close();
