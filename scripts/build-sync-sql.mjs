#!/usr/bin/env node
// Turns Salesforce exports into db/sql/06_sync.sql, which stamps real Salesforce IDs onto the
// raw tables. Run after: npm run sf:export  (see docs/SETUP_SALESFORCE.md)
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../salesforce/exports/', import.meta.url));
const out = fileURLToPath(new URL('../db/sql/06_sync.sql', import.meta.url));
const read = name => {
  const p = dir + name;
  if (!fs.existsSync(p)) { console.error(`Missing ${p}. Run: npm run sf:export`); process.exit(1); }
  const body = JSON.parse(fs.readFileSync(p, 'utf8'));
  return body.result?.records || [];
};
const lit = v => `'${String(v).replace(/'/g, "''")}'`;
const key = d => (d || '').replace(/^SalesLore demo:\s*/, '').trim();
const idOk = v => /^[a-zA-Z0-9]{15,18}$/.test(v);

const lines = ['-- 06_sync.sql: generated by scripts/build-sync-sql.mjs from your Salesforce org. Git-ignored.', 'BEGIN;'];
let n = 0;
for (const r of read('accounts.json')) if (idOk(r.Id) && key(r.Description)) { lines.push(`UPDATE raw.accounts SET sf_account_id = ${lit(r.Id)} WHERE account_id = ${lit(key(r.Description))};`); n++; }
for (const r of read('opportunities.json')) if (idOk(r.Id) && key(r.Description)) { lines.push(`UPDATE raw.opportunities SET sf_opportunity_id = ${lit(r.Id)} WHERE account_id = ${lit(key(r.Description))};`); n++; }
lines.push('COMMIT;', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote db/sql/06_sync.sql with ${n} updates. Apply it with: npm run db:setup`);
